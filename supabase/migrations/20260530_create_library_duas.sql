-- Create library_duas table
create table if not exists public.library_duas (
  id text primary key,
  source text not null,
  text_ru text not null,
  text_ar text,
  transcription text,
  reference text
);

-- Enable Row Level Security (RLS)
alter table public.library_duas enable row level security;

-- Allow public read access to library duas (for unauthenticated and authenticated users)
create policy "Anyone can view library duas"
  on public.library_duas for select
  to anon, authenticated
  using (true);

